# 🔴 daily_prices 에는 종목이 아닌 행이 섞여 있다: KOSPI·KOSDAQ(각 1,375행)·
#    KS11·KQ11(각 601행). core/regime/index_refresh.py 가 국면 판정용으로 적재하는
#    정당한 데이터지만, 소비자가 이 행을 **종목으로 취급하면 안 된다.**
#
# 🔑 이름 목록(NOT IN ('KOSPI', ...))으로 막지 말 것 — 지수가 하나 늘 때마다 뚫린다.
#    실제로 두 번 뚫렸다(2024년 KS11/KQ11 추가, 2026-06 KOSDAQ 추가).
#    그래서 KRX 단축코드의 **형식**으로 막는다 = 첫 글자가 숫자 + 영숫자 6자리.
#      포함: 005930(보통주) · 00088K·37550L(신형우선주) · 0001A0(신형 상장코드)
#      제외: KOSPI · KOSDAQ · KS11 · KQ11 — 지수 의사행은 전부 문자로 시작한다.
#
# ⚠️ 좁히지 말 것. KRX 코드 체계가 두 번 넓어졌고, 술어를 좁게 잡을 때마다
#    실제 상장 종목이 통째로 배제됐다. 실측(2026-08-12):
#      `^[0-9]{6}$`        → 신형우선주 10종 배제. 마지막 일봉이 전부 2024-02-29
#                            에서 멈춰 있었다(774행, 2년 5개월 미수집).
#      `^[0-9]{5}[0-9A-Z]$` → 중간이 영문인 신형 상장코드 54종목 배제
#                            (0001A0 덕양에너젠 · 0007C0 아크릴 · 0030R0 대신밸류리츠).
#                            FDR 상장목록에 이름과 함께 실재하는 종목이다.
#
# ⚠️ 이 상수를 f-string/.format() **템플릿 리터럴 안에** 직접 적지 말 것 —
#    `{5}` 가 치환 필드로 해석된다. 변수로 끼워넣는 것은 안전하다.
#
# 연구 쪽 사본 lib/universe_filter.py 는 `^[0-9]{5}[0-9A-Z]$` 로 좁아 54종목을
# 놓친다(그 파일 docstring 의 "실제 상장 종목 전부"는 사실이 아니다). 연구 경로
# 정정은 별건 — 라이브 수집 경로는 여기 상수만 본다.
STOCK_CODE_RE = r"^[0-9][0-9A-Z]{5}$"
SQL_STOCK_ONLY = "stock_code ~ '^[0-9][0-9A-Z]{5}$'"
